// Реквизитите на получателя във фактурата.
//
// Поводът: фактурите излизаха с кратко работно име („Емо", „Никола"), без ЕГН и
// без адрес. И трите са задължителни по чл.114 ЗДДС, а данните ги имаше —
// в договора, попълнени от личната карта при подписването. Фактурата просто не
// ги гледаше: четеше само `properties.invoice_recipient`, празен при 36 от 38
// имота.
const { buildRecipient, idLabel } = require('../routes/invoices');

const CONTRACT = {
  tenant_name: 'Илия Петров Илиев',
  tenant_egn: '9312093028',
  tenant_address: 'жк. МЛАДОСТ 4 460А вх.2 ет.4 ап.17, гр. СОФИЯ',
  tenant_mol: '',
};
const PROP = { 'наемател': 'ИЛИЯ ИЛИЕВ' };

describe('откъде идват данните на получателя', () => {
  it('договорът попълва трите имена, ЕГН и адрес, когато настройката е празна', () => {
    const r = buildRecipient({}, CONTRACT, PROP);
    expect(r.name).toBe('Илия Петров Илиев');
    expect(r.eik).toBe('9312093028');
    expect(r.address).toBe('жк. МЛАДОСТ 4 460А вх.2 ет.4 ап.17, гр. СОФИЯ');
  });

  // Изричната настройка е за случаите, когато фактурата е на фирма, различна
  // от наемателя — тя трябва да остане над договора.
  it('изричната настройка на имота бие договора', () => {
    const r = buildRecipient(
      { name: 'СТРОЙМАРКЕТ ООД', eik: '123456789', address: 'София, бул. X 1', mol: 'Петър Петров' },
      CONTRACT, PROP);
    expect(r.name).toBe('СТРОЙМАРКЕТ ООД');
    expect(r.eik).toBe('123456789');
    expect(r.mol).toBe('Петър Петров');
  });

  it('частично попълнена настройка взима останалото от договора', () => {
    const r = buildRecipient({ name: 'Фирма ЕООД' }, CONTRACT, PROP);
    expect(r.name).toBe('Фирма ЕООД');
    expect(r.eik).toBe('9312093028');
    expect(r.address).toContain('МЛАДОСТ');
  });

  it('без договор пада до полето „наемател", за да не е празно', () => {
    const r = buildRecipient({}, null, PROP);
    expect(r.name).toBe('ИЛИЯ ИЛИЕВ');
    expect(r.eik).toBe('');
    expect(r.address).toBe('');
  });

  it('без нищо не хвърля и връща празни низове, а не undefined', () => {
    const r = buildRecipient(null, null, null);
    expect(r).toEqual({ name: '', address: '', eik: '', mol: '' });
    for (const v of Object.values(r)) expect(typeof v).toBe('string');
  });
});

describe('етикет на идентификатора', () => {
  // Досега винаги се печаташе „ЕИК:", включително за физически лица.
  it('десет цифри е ЕГН', () => {
    expect(idLabel('9312093028', '')).toBe('ЕГН');
  });

  it('девет цифри е ЕИК', () => {
    expect(idLabel('207291184', '')).toBe('ЕИК');
  });

  it('тринайсет цифри също е ЕИК', () => {
    expect(idLabel('2072911840001', '')).toBe('ЕИК');
  });

  // МОЛ има само дружество — това е по-силен признак от дължината.
  it('наличието на МОЛ прави получателя дружество', () => {
    expect(idLabel('9312093028', 'Иво Лазаров')).toBe('ЕИК');
  });

  // Чуждестранен документ не бива да се надписва с български реквизит.
  it('белгийският номер на Марио не е нито ЕГН, нито ЕИК', () => {
    expect(idLabel('87.05.23-081.24', '')).toBe('ЕГН/ЕИК');
  });

  it('празна стойност не хвърля', () => {
    expect(idLabel('', '')).toBe('ЕГН/ЕИК');
    expect(idLabel(null, null)).toBe('ЕГН/ЕИК');
  });

  it('интервалите не променят разпознаването', () => {
    expect(idLabel('  9312093028  ', '')).toBe('ЕГН');
  });
});
