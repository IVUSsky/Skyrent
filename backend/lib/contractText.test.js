const { tidyContractText } = require('./contractText');

describe('двойното „г." след дата', () => {
  it('полето носи „г.", бланката добавя още едно', () => {
    expect(tidyContractText('Днес, 02.11.2026 г. г., в град София'))
      .toBe('Днес, 02.11.2026 г., в град София');
  });

  it('бланка с „год." запазва своята дума', () => {
    expect(tidyContractText('изд. на: 01.02.2020 г. год.')).toBe('изд. на: 01.02.2020 год.');
  });

  it('правилната дата не се пипа', () => {
    const ok = 'Срокът е до 04.11.2027 г. и не се променя.';
    expect(tidyContractText(ok)).toBe(ok);
    expect(tidyContractText('изд. на: 01.02.2020 год.')).toBe('изд. на: 01.02.2020 год.');
  });

  it('оправя всички срещания, не само първото', () => {
    expect(tidyContractText('от 05.11.2026 г. г. до 04.11.2027 г. г.'))
      .toBe('от 05.11.2026 г. до 04.11.2027 г.');
  });

  it('„г." без дата пред него е друга дума и не се пипа', () => {
    expect(tidyContractText('гр. София, кв. Г. Делчев')).toBe('гр. София, кв. Г. Делчев');
  });

  it('празен текст не гърми', () => {
    expect(tidyContractText('')).toBe('');
    expect(tidyContractText(null)).toBe('');
  });
});
