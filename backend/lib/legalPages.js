// Публични правни страници (политика за поверителност, условия).
//
// Поводът: Enable Banking иска публичен адрес на политика за поверителност при
// регистрация на приложение. На skycapital.pro нямаше такава страница — всеки
// адрес връщаше обвивката на приложението (еднакъв title и размер).
//
// Страниците се сервират като статичен HTML от бекенда, за да работят и без
// JavaScript, и да не зависят от маршрутизацията на фронтенда.

function esc(s) {
  return String(s == null ? '' : s).replace(/[&<>"']/g, c =>
    ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));
}

