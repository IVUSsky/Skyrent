// Дребни оправяния на текста СЛЕД попълването на бланката.
//
// Датите в полетата вече носят „г." (fmtDate), а бланките често добавят
// още едно: „Днес, 02.11.2026 г. г.". Поправката е тук, а не в бланките,
// защото бланките са данни — всяка организация си има свои и утре някой
// пак ще напише „{{ДАТА_НАЧАЛО}} г.".
//
// Запазва се ДУМАТА НА БЛАНКАТА („г." или „год."), а се маха автоматично
// добавената — така авторът на бланката получава каквото е написал.

const tidyDates = (text) => String(text == null ? '' : text)
  .replace(/(\d{4})\s*г\.\s*(г\.|год\.)/gu, '$1 $2');

const tidyContractText = (text) => tidyDates(text);

module.exports = { tidyContractText, tidyDates };
